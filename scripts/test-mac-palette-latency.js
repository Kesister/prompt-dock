const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
if (process.platform !== 'darwin') throw Error('Run on macOS');
const root = path.resolve(__dirname, '..');
const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'prompt-dock-palette-latency-'));
const contents = path.join(directory, 'LatencyTarget.app/Contents');
fs.mkdirSync(path.join(contents, 'MacOS'), { recursive: true });
fs.writeFileSync(path.join(contents, 'Info.plist'), '<?xml version="1.0"?><plist version="1.0"><dict><key>CFBundleIdentifier</key><string>com.codex.promptdock.latencyfixture</string><key>CFBundleName</key><string>Prompt Dock Latency Fixture</string><key>CFBundleExecutable</key><string>LatencyTarget</string><key>CFBundlePackageType</key><string>APPL</string><key>CFBundleVersion</key><string>1</string></dict></plist>');
const target = path.join(contents, 'MacOS/LatencyTarget');
const compile = spawnSync('xcrun', ['swiftc', '-module-cache-path', path.join(root, 'build/module-cache'), '-O', path.join(root, 'scripts/native-paste-target.swift'), '-o', target], { stdio: 'inherit' });
if (compile.status) process.exit(compile.status);
const env = { ...process.env, PROMPT_DOCK_LATENCY_PROFILE: directory, PROMPT_DOCK_LATENCY_TARGET: target };
if (process.argv[2]) env.PROMPT_DOCK_LATENCY_APP = path.resolve(process.argv[2]);
delete env.ELECTRON_RUN_AS_NODE; delete env.PROMPT_DOCK_NATIVE_TEST; delete env.PROMPT_DOCK_SMOKE_TEST;
const log = fs.openSync(path.join(directory, 'latency.log'), 'w');
const result = spawnSync(require('electron'), [path.join(root, 'tests/mac-palette-latency.js')], { cwd: root, env, stdio: ['ignore', log, log], timeout: 60000 });
fs.closeSync(log);
const evidence = path.join(directory, 'results.json');
if (fs.existsSync(evidence)) console.log(fs.readFileSync(evidence, 'utf8'));
else console.log(fs.readFileSync(path.join(directory, 'latency.log'), 'utf8'));
console.log(`Latency evidence: ${directory}`);
process.exitCode = result.status === 0 ? 0 : 1;
